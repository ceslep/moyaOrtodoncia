export function findCoordByNombre(nombre: string): MunicipioCoord | undefined {
  const lower = nombre.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '');
  return coords.find(c => c.nombre.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '') === lower);
}

export function searchCoord(query: string): MunicipioCoord[] {
  const lower = query.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '');
  return coords.filter(c =>
    c.nombre.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '').includes(lower) ||
    c.codigo.includes(query)
  );
}

